export function EntryGlyph({ name }: { name: string }): React.JSX.Element | null {
  const Glyph = glyphs[name as keyof typeof glyphs];
  return Glyph ? <Glyph size={20} strokeWidth={1.75} aria-hidden="true" /> : null;
}
export function isEntryGlyph(name: string): boolean { return Object.hasOwn(glyphs, name); }
